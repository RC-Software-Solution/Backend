const redisPublisher = require('../services/redisPublisher');
const userServiceClient = require('../services/userServiceClient');
const { Op } = require('sequelize');

const { Order, Order_Item, Meal_Session, sequelize } = require('../models');

exports.createOrder = async (req, res) => {
  const { customer_id, items, total_price, meal_time } = req.body;

  try {
    if (
      !customer_id ||
      !items ||
      !Array.isArray(items) ||
      items.length === 0 ||
      !total_price ||
      !meal_time
    ) {
      return res
        .status(400)
        .json({ message: 'Missing or invalid required fields' });
    }
    //check for unpaid orders
    const unpaidOrders = await Order.count({
      where: {
        customer_id,
        payment_status: 'pending', //if this way sucks, add another column to the user table to keep track of unpaid orders
      },
    });
    if (unpaidOrders > 2) {
      return res
        .status(400)
        .json({ message: 'You have more than two unpaid order' });
    }

    // Verify customer exists and get area_id from user-service
    let customerAreaId = null;
    try {
      const customerData = await userServiceClient.getUserById(customer_id);
      customerAreaId = customerData.area_id;
      console.log(
        `Fetched area_id ${customerAreaId} for customer ${customer_id}`
      );
    } catch (error) {
      console.error(
        'Error fetching customer data from user-service:',
        error.message
      );
      return res
        .status(404)
        .json({ message: 'Customer not found or user-service unavailable' });
    }

    const mealSession = await Meal_Session.findOne({
      where: {
        meal_time,
        date: sequelize.literal('CURDATE()'),
      },
    });
    if (!mealSession) {
      return res.status(400).json({ message: 'Meal session not found' });
    }

    // Calculate total quantity and validate order limit
    const totalQuantity = items.reduce((acc, item) => acc + item.quantity, 0);
    if (mealSession.current_orders + totalQuantity > mealSession.order_limit) {
      return res.status(400).json({ message: 'Order limit reached' });
    }

    // Create order and items in a transaction
    const order = await sequelize.transaction(async (t) => {
      const newOrder = await Order.create(
        {
          customer_id,
          area_id: customerAreaId,
          total_price,
          meal_time,
        },
        { transaction: t }
      );

      //Create order items using association
      //this createOrder_item method is generated by sequelize itself when using as: in defining the association. But since it is in singular form, use a loop to insert all items
      for (const item of items) {
        await newOrder.createOrder_item(
          {
            quantity: item.quantity,
            food_name: item.food_name,
            food_description: item.food_description,
            meal_type: item.meal_type,
            price: item.price,
          },
          { transaction: t }
        );
      }

      // Increment current_orders once
      await mealSession.increment('current_orders', {
        by: totalQuantity,
        transaction: t,
      });

      return newOrder;
    });

    const updatedSession = await Meal_Session.findOne({
      where: {
        meal_time,
        date: sequelize.literal('CURDATE()'),
      },
    });
    const remainingOrders =
      updatedSession.order_limit - updatedSession.current_orders;
    console.log('Meal time:', meal_time);
    console.log('Remaining orders:', remainingOrders);

    await redisPublisher.publishOrderUpdate({
      meal_time,
      remainingOrders,
    });

    return res
      .status(201)
      .json({ message: 'Order placed successfully', order_id: order.id });
  } catch (error) {
    console.error('Error placing order:', error);
    return res.status(500).json({ message: 'Server error' });
  }
};

exports.editOrder = async (req, res) => {
  const { items, total_price } = req.body;
  const { order_id } = req.params;

  try {
    if (
      !items ||
      !Array.isArray(items) ||
      items.length === 0 ||
      !total_price ||
      !order_id
    ) {
      return res
        .status(400)
        .json({ message: 'Missing or invalid required fields' });
    }
    //get the existing order
    const order = await Order.findByPk(order_id);
    if (!order) {
      return res.status(404).json({ message: 'Order not found' });
    }

    // Verify order ownership (assuming req.user.id from auth middleware)
    // if (order.customer_id !== req.user?.id) {
    //   return res.status(403).json({ message: 'Unauthorized to edit this order' });
    // }

    //get the meal session
    const mealSession = await Meal_Session.findOne({
      where: {
        meal_time: order.meal_time,
        date: sequelize.literal('CURDATE()'),
      },
    });
    if (!mealSession) {
      return res.status(404).json({ message: 'Meal session not found' });
    }

    //validate time window
    // this block can be ignored if the edit button can be deactivated outside the meal session time window in frontend
    const now = new Date();
    const startTime = new Date(
      `${now.toDateString()} ${mealSession.start_time}`
    );
    const endTime = new Date(`${now.toDateString()} ${mealSession.end_time}`);
    if (now < startTime || now > endTime) {
      return res.status(400).json({
        message: 'Order cannot be edited outside the meal session time window',
      });
    }

    //getting existing order items
    const existingItems = await Order_Item.findAll({
      where: { order_id },
    });
    const oldQuantity = existingItems.reduce(
      (acc, item) => acc + item.quantity,
      0
    );
    const newQuantity = items.reduce((acc, item) => acc + item.quantity, 0);
    const quantityDifference = newQuantity - oldQuantity;

    //validate order limit
    if (
      mealSession.current_orders + quantityDifference >
      mealSession.order_limit
    ) {
      return res
        .status(400)
        .json({ message: 'Order limit exceeded. Cannot add these items.' });
    }

    //transactional update
    await sequelize.transaction(async (t) => {
      //update total price
      await order.update({ total_price }, { transaction: t });

      //remove old items
      await Order_Item.destroy({ where: { order_id }, transaction: t });

      //add new items
      for (const item of items) {
        await order.createOrder_item(
          {
            quantity: item.quantity,
            food_name: item.food_name,
            food_description: item.food_description,
            meal_type: item.meal_type,
            price: item.price,
          },
          { transaction: t }
        );
      }

      if (quantityDifference !== 0) {
        await mealSession.increment('current_orders', {
          by: quantityDifference,
          transaction: t,
        });

        await redisPublisher.publishOrderUpdate({
          meal_time: order.meal_time,
          remainingOrders:
            mealSession.order_limit -
            (mealSession.current_orders + quantityDifference),
        });
      }
    });

    return res.status(200).json({ message: 'Order updated successfully' });
  } catch (error) {
    console.error('Error fetching order:', error);
    return res.status(500).json({ message: 'Server error' });
  }
};

exports.deleteOrder = async (req, res) => {
  const { order_id } = req.params;

  try {
    if (!order_id) {
      return res.status(400).json({ message: 'Invalid order_id' });
    }
    const order = await Order.findByPk(order_id, {
      include: [{ model: Order_Item, as: 'order_items' }],
    });
    if (!order) {
      return res.status(404).json({ message: 'Order not found' });
    }

    if (!order.order_items || order.order_items.length === 0) {
      return res.status(400).json({ message: 'Order has no items to delete' });
    }

    const mealTime = order.meal_time;
    if (!mealTime) {
      return res.status(400).json({ message: 'Meal time not found in order' });
    }

    const mealSession = await Meal_Session.findOne({
      where: {
        meal_time: mealTime,
        date: sequelize.literal('CURDATE()'),
      },
    });
    if (!mealSession) {
      return res.status(404).json({ message: 'Meal session not found' });
    }

    const now = new Date();
    const startTime = new Date(
      `${now.toDateString()} ${mealSession.start_time}`
    );
    const endTime = new Date(`${now.toDateString()} ${mealSession.end_time}`);

    if (now < startTime || now > endTime) {
      return res
        .status(403)
        .json({ message: 'Order can only be deleted within session time' });
    }

    // Count how many items are being deleted
    const totalQty = order.order_items.reduce(
      (acc, item) => acc + item.quantity,
      0
    );

    // Delete order and items in a transaction
    await sequelize.transaction(async (t) => {
      await order.destroy({ transaction: t });
      await mealSession.decrement('current_orders', {
        by: totalQty,
        transaction: t,
      });
    });

    const updatedSession = await Meal_Session.findByPk(mealSession.id);
    await redisPublisher.publishOrderUpdate({
      meal_time: updatedSession.meal_time,
      remainingOrders:
        updatedSession.order_limit - updatedSession.current_orders,
    });

    return res.status(200).json({ message: 'Order deleted successfully' });
  } catch (error) {
    console.error('Error deleting order:', error);
    return res.status(500).json({ message: 'Server error' });
  }
};

exports.getOrders = async (req, res) => {
  const {
    type,
    meal_time,
    date,
    status,
    meal_type,
    limit,
    offset,
    customer_id,
    area_id,
    payment_status,
  } = req.query;

  try {
    // Log input parameters
    console.log('Received query parameters:', {
      type,
      meal_time,
      date,
      status,
      meal_type,
      limit,
      offset,
      customer_id,
      user_role: req.user?.role,
      user_id: req.user?.id
    });

    // Basic input validation
    if (!type) {
      console.log('Validation failed: type parameter is required');
      return res.status(400).json({ message: 'type parameter is required' });
    }
    if (type === 'current' && !meal_time) {
      console.log('Validation failed: meal_time is required for type=current');
      return res
        .status(400)
        .json({ message: 'meal_time is required for type=current' });
    }

    // Role-based access control
    const userRole = req.user?.role;
    const userId = req.user?.id;
    const userAreaId = req.user?.area_id;

    // Build where clause based on user role
    const where = {};
    
    if (userRole === 'customer') {
      // Customers can only see their own orders
      where.customer_id = userId;
      console.log('Customer access: filtering by customer_id =', userId);
      
    } else if (userRole === 'delivery_person') {
      // Delivery persons can see orders in their assigned area
      if (area_id && area_id !== userAreaId.toString()) {
        return res.status(403).json({ 
          message: 'You can only view orders in your assigned area' 
        });
      }
      where.area_id = userAreaId;
      console.log('Delivery person access: filtering by area_id =', userAreaId);
      
    } else if (userRole === 'admin' || userRole === 'super_admin') {
      // Admins can see all orders, but can filter by customer_id or area_id if provided
      if (customer_id) {
        where.customer_id = customer_id;
        console.log('Admin access: filtering by customer_id =', customer_id);
      }
      if (area_id) {
        where.area_id = area_id;
        console.log('Admin access: filtering by area_id =', area_id);
      }
      console.log('Admin access: no restrictions applied');
      
    } else {
      return res.status(403).json({ 
        message: 'Invalid user role or insufficient permissions' 
      });
    }

    // Normalize meal_time to lowercase and validate against ENUM
    const validMealTimes = ['breakfast', 'lunch', 'dinner'];
    const normalizedMealTime = meal_time ? meal_time.toLowerCase() : null;
    if (type === 'current' && !validMealTimes.includes(normalizedMealTime)) {
      console.log('Validation failed: Invalid meal_time', {
        meal_time,
        normalizedMealTime,
      });
      return res.status(400).json({
        message: 'Invalid meal_time, must be one of: breakfast, lunch, dinner',
      });
    }
    console.log('Normalized meal_time:', normalizedMealTime);

    const include = [
      {
        model: Order_Item,
        as: 'order_items',
        required: false, // Include orders even if they have no items
      },
    ];

    // Handle filter types
    if (type === 'current') {
      // Validate meal session existence
      const targetDate = date || new Date().toISOString().split('T')[0]; // Use current date in YYYY-MM-DD format
      console.log('Querying Meal_Session with:', {
        meal_time: normalizedMealTime,
        targetDate,
      });
      const mealSession = await Meal_Session.findOne({
        where: {
          meal_time: normalizedMealTime,
          date: targetDate,
        },
      });
      console.log(
        'Meal_Session result:',
        mealSession ? mealSession.toJSON() : null
      );

      if (!mealSession) {
        console.log('No Meal_Session found for:', {
          meal_time: normalizedMealTime,
          targetDate,
        });
        return res.status(404).json({ message: 'Meal session not found' });
      }

      where.meal_time = normalizedMealTime;
      // Fix the date filtering to properly compare dates using Sequelize date functions
      where.created_at = {
        [Op.gte]: sequelize.literal(`DATE('${targetDate}')`),
        [Op.lte]: sequelize.literal(
          `DATE('${targetDate}') + INTERVAL 1 DAY - INTERVAL 1 SECOND`
        ),
      };

      console.log('Date filtering details:', {
        targetDate,
        whereCreatedAt: where.created_at,
      });
    } else if (type === 'pending') {
      where.payment_status = 'pending';
    } else {
      console.log('Validation failed: Invalid type parameter', { type });
      return res.status(400).json({ message: 'Invalid type parameter' });
    }

    // Optional filters
    if (status) {
      where.status = status;
      console.log('Applying status filter:', status);
    }
    if (payment_status) {
      where.payment_status = payment_status;
      console.log('Applying payment_status filter:', payment_status);
    }
    if (meal_type) {
      include[0].where = include[0].where || {};
      include[0].where.meal_type = meal_type;
      console.log('Applying meal_type filter:', meal_type);
    }

    // Pagination
    const queryLimit = parseInt(limit) || 10;
    const queryOffset = parseInt(offset) || 0;
    if (
      isNaN(queryLimit) ||
      queryLimit < 1 ||
      isNaN(queryOffset) ||
      queryOffset < 0
    ) {
      console.log('Validation failed: Invalid limit or offset', {
        limit,
        offset,
      });
      return res.status(400).json({ message: 'Invalid limit or offset' });
    }

    // Log query details
    console.log('Querying orders with:', {
      where,
      include,
      limit: queryLimit,
      offset: queryOffset,
      order: [['created_at', 'DESC']],
    });

    // Debug: Log the final where clause for troubleshooting
    console.log('Final where clause:', where);

    // Fetch orders
    const orders = await Order.findAll({
      where,
      include,
      limit: queryLimit,
      offset: queryOffset,
      order: [['created_at', 'DESC']],
    });

    // Log fetched orders
    console.log(
      'Orders found:',
      orders.map((order) => order.toJSON())
    );

    return res.status(200).json({
      message: 'Orders retrieved successfully',
      orders,
      limit: queryLimit,
      offset: queryOffset,
    });
  } catch (error) {
    console.error('Error fetching orders:', {
      error: error.message,
      stack: error.stack,
      customer_id,
      type,
      meal_time,
      date,
    });
    return res.status(500).json({ message: 'Server error' });
  }
};

exports.updatePaymentStatus = async (req, res) => {
  const { order_id } = req.params;
  const { payment_status } = req.body;

  try {
    if (!order_id) {
      return res.status(400).json({ message: 'order_id is required' });
    }

    if (
      !payment_status ||
      !['pending', 'paid', 'unpaid'].includes(payment_status)
    ) {
      return res.status(400).json({
        message:
          'Invalid payment_status. Must be one of: pending, paid, unpaid',
      });
    }

    const order = await Order.findByPk(order_id);
    if (!order) {
      return res.status(404).json({ message: 'Order not found' });
    }

    await order.update({ payment_status });

    res.status(200).json({
      message: 'Payment status updated successfully',
      order_id,
      payment_status,
      order: {
        id: order.id,
        customer_id: order.customer_id,
        area_id: order.area_id,
        payment_status: order.payment_status,
        status: order.status,
        total_price: order.total_price,
        meal_time: order.meal_time,
      },
    });
  } catch (error) {
    console.error('Error updating payment status:', error);
    res.status(500).json({ message: 'Server error' });
  }
};
